import Foundation

/// The place Home's sky is a picture of — "the painted hill": a river valley,
/// the hills between, a knoll and one tree against the setting sun — as the
/// numbers it was set by hand with. There are two of them. The Duo's is one
/// world with two windows on it: the closed cover shows it from the anchor
/// window's leading edge, and the open spread's phone page is that same
/// picture, with the world running on to the left across the leading page.
/// The slab iPhone's is a separate arrangement of the same place, composed
/// for a tall narrow display (its own horizon, no river, one cloud).
///
/// Coordinates are points. World x is 0 at the anchor window's leading edge
/// and y is the display's y in the REST pose (the everyday view). The night's
/// view — looking up — is the same picture lowered by `drop` and turned by
/// `turn`; "looked-up points" are display points in that pose.
///
/// Every number here is the sky lab's (`design/sky-lab/skies/hill-painted.js`,
/// `DUO` and `SLAB`), and none is to be changed by eye: `SkyWorldTests`
/// compares each with what the lab's own code says (`SkyCoreFixturesMoment`,
/// regenerated by `design/sky-lab/tools/swift-fixtures/moment.mjs`). The
/// crest lines under the sky — what holds his stars up — are `Skyline`'s.
/// Left in the lab until the painting is ported: the near planes' crests,
/// the spurs' feet, the mist, the river.
struct SkyWorld: Equatable {
    /// Which of the two worlds: the Duo's (cover and spread) or the slab's.
    enum Kind: String, Equatable, CaseIterable {
        case duo, slab
    }

    // MARK: The pieces

    /// A plane of the picture: the shapes that move together when the camera
    /// does. Looking up, every plane only TRANSLATES — the far ones with the
    /// sky, the near ones faster — and nothing is repainted for the move.
    struct Plane: Equatable {
        /// Far to near. `sky` is the tall sky itself, with his stars, the
        /// sun, the moon and the clouds on it; the tree is a layer of its own
        /// over `knoll` and moves as it does.
        enum ID: String, Equatable, CaseIterable {
            case sky, far, mid, knoll, near, fore
        }

        /// Which plane this is.
        let id: ID
        /// How much of the world's `drop` this plane sinks by, looking up.
        let sink: CGFloat
        /// How much of the world's `turn` this plane slides by, looking up.
        let slide: CGFloat
        /// Points of parallax at a full tilt of the phone (±1 on each axis).
        /// The sky's is negative: it leans the other way from the land.
        let tilt: CGSize
    }

    /// The one tree, on the knoll.
    struct Tree: Equatable {
        /// World x of its trunk.
        let x: CGFloat
        /// How tall it stands.
        let height: CGFloat
        /// Rest-pose y of its foot: the knoll's crest under the trunk, and
        /// 1.2 pt into the ground — to a thousandth of a point, as read off
        /// the lab's page (`Skyline.treeFoot(at:)` works out the same foot
        /// from the crest itself; `SkylineTests` holds the two together).
        let foot: CGFloat
    }

    /// "✦ Night 143": the page's one line, at the foot on the side away from
    /// the tree, while the cards are away at bedtime.
    struct Caption: Equatable {
        /// Its leading edge and baseline, in looked-up points.
        let origin: CGPoint
        /// The type's size.
        let size: CGFloat
    }

    /// How far left a low sun or moon is brought on its setting side. On a
    /// slab the baseline's x sets a body at x 386, behind the gear button in
    /// every season; under 12° of altitude it is brought left by this many
    /// points (all of it by 6°), so the sun comes down behind the crown's
    /// right shoulder — the picture this sky is for.
    struct Sets: Equatable {
        /// The sun then sets at x 324, limbs across the crown.
        let sun: CGFloat
        /// The moon by less: it sets at x 340, clear of the gear and of the
        /// crown.
        let moon: CGFloat
    }

    /// A cloud: a quiet bank drawn the way this picture draws a hill, from
    /// ONE top contour set by hand. None stands whole and compact in a slot
    /// of the UI: a closed small cloud under the status glyphs is a weather
    /// symbol.
    struct Cloud: Equatable {
        /// Which view a cloud belongs to. `rest`: the everyday view's — it
        /// leaves as the camera looks up, so nothing stands among his stars.
        /// `up`: the looked-up view's — one broken bar, low, left of the
        /// tree; it arrives with the camera. `always`: the leading page's.
        enum Belongs: String, Equatable {
            case rest, up, always
        }

        /// One mass of the top contour: a few of unequal size, never a run of
        /// like scallops.
        struct Mass: Equatable {
            /// Its centre along the cloud, −1 … 1.
            let centre: CGFloat
            /// Its half-width, in the same measure.
            let halfWidth: CGFloat
            /// Its height, 0 … 1 of the cloud's `rise`.
            let height: CGFloat
        }

        /// Its name in the lab: `strip`, `gap`, `bank`, `bar`, `low`.
        let id: String
        /// World x of its designed place: the middle of the lane it drifts
        /// along.
        let x: CGFloat
        /// Its foot, in points over the horizon.
        let lift: CGFloat
        /// Its box: this far across…
        let length: CGFloat
        /// …and this tall. The lowest third lets go into the air: a cloud
        /// has no base, as a plane of land has none in the mist at its foot.
        let rise: CGFloat
        /// How far it drifts, end to end, from the sunset side.
        let span: CGFloat
        /// Seconds for one drift…
        let period: TimeInterval
        /// …and where in it the cloud is at time 0, 0 … 1.
        let phase: Double
        /// The hand: how far the contour wanders.
        let wobble: CGFloat
        /// The view it belongs to.
        let belongs: Belongs
        /// A high cloud is lit and shaded from the high-cloud colours.
        let high: Bool
        /// The top contour's masses: one large, one of about half that, a
        /// small outlier, their shoulders, and the long lens they stand on.
        let top: [Mass]
    }

    /// One box of the looked-up sky his stars are laid out in. The looked-up
    /// sky is the night's picture, so it is laid out for THAT view, top to
    /// bottom: a box's share of his stars is its area × `density`. Thickest
    /// overhead and thinning toward the land, as a sky is.
    struct StarBox: Equatable {
        /// A run of x inside the box, and how much of the box's stars it
        /// takes for its width (1 is an even share).
        struct Column: Equatable {
            /// From this x…
            let x0: CGFloat
            /// …to this one, looked-up points.
            let x1: CGFloat
            /// Its share for its width.
            let weight: Double
        }

        /// The box's sides, in looked-up points: leading…
        let x0: CGFloat
        /// …and trailing.
        let x1: CGFloat
        /// Its top…
        let y0: CGFloat
        /// …and its foot (a star never sits lower than the land lets it).
        let y1: CGFloat
        /// How thick with stars it is, for its area.
        let density: Double
        /// Empty: one even column, the box's whole width.
        let columns: [Column]
    }

    // MARK: The world

    /// Which world this is.
    let kind: Kind
    /// The window the world was composed for: the anchor window's width and
    /// the display's height (the Duo's is the cover's; the spread is 9 pt
    /// shorter, and everything is laid out from the top).
    let anchor: CGSize
    /// The horizon at rest.
    let horizon: CGFloat
    /// Looking up lowers the horizon this far — the camera's drop.
    let drop: CGFloat
    /// …and the turn slides the far world this far left. On the Duo it takes
    /// the tree to x 318, clear of the tab capsule with the cards away: the
    /// bare poster of the bedtime moment.
    let turn: CGFloat
    /// Points of sky the twilight's eight stops span.
    let skySpan: CGFloat
    /// Sun and moon: how high the zenith stands over the horizon, in points
    /// of the tall sky.
    let zenith: CGFloat
    /// The tree against the setting sun: the picture's subject by day.
    let tree: Tree
    /// The top of the knoll, as set by hand: where the tree stands.
    let knollSummit: CGPoint
    /// Tonight's star at rest: above the tree's left shoulder (world points).
    let tonight: CGPoint
    /// …and looking up: in the strip's clear window between the status icons
    /// and the tab capsule on the Duo, in the header band between his name
    /// and the gear on the slab (looked-up points).
    let tonightUp: CGPoint
    /// The first night's star, looking up: in the header's clear gap, between
    /// his name and the gear. The Duo's only.
    let firstNightUp: CGPoint?
    /// The sun's disc…
    let sunRadius: CGFloat
    /// …and the moon's, a little smaller.
    let moonRadius: CGFloat
    /// The slab's only: see `Sets`. Nil where the baseline's x stands.
    let sets: Sets?
    /// His stars are drawn at this size (the slab's are a little smaller).
    let starScale: CGFloat
    /// Where "✦ Night 143" stands.
    let caption: Caption
    /// The tall sky's own plane.
    let sky: Plane
    /// The land, far to near.
    let planes: [Plane]
    /// The clouds, each on the sky's plane.
    let clouds: [Cloud]
    /// His stars keep this far inside the anchor window's sides…
    let starInset: CGFloat
    /// …and under this y, looking up (the slab's: under the status bar).
    let starTop: CGFloat

    // MARK: The lab's layout

    /// THE LAB'S LAYOUT, not the app's: the phone page's cards in the
    /// standing layouts, in looked-up points — the three that are there
    /// asleep and awake (Today, the Feed and Diaper tiles), then the night's
    /// own (asleep: the sleep card and the card under it; awake for a feed:
    /// the Sleep tile and the timeline). What a four-point star keeps clear
    /// of. The table is fixed, so a star's place does not change when he
    /// wakes. To be replaced by the app's own rows, measured once per layout,
    /// at stage 0b.
    let labCards: [CGRect]
    /// THE LAB'S LAYOUT: which of `labCards` are glass.
    let labGlass: [Int]
    /// THE LAB'S LAYOUT: where the Duo's strip window begins, from the
    /// anchor window's leading edge. Nil on a slab, which has no strip.
    let labStripWindow: CGFloat?

    // MARK: What follows from it

    /// The horizon, looking up.
    var horizonUp: CGFloat { horizon + drop }

    /// The tall sky runs from above the top of the looked-up view…
    var skyTop: CGFloat { -(drop + 26) }
    /// …to under the horizon (rest-pose y, both).
    var skyFoot: CGFloat { horizon + 30 }

    /// Points of world painted beyond the display's leading
    /// edge, for the tilt and the near planes' slide…
    static let marginLeading: CGFloat = 34
    /// …and beyond its trailing edge.
    static let marginTrailing: CGFloat = 44

    /// The plane with this name.
    func plane(_ id: Plane.ID) -> Plane {
        if id == .sky { return sky }
        return planes.first { $0.id == id } ?? sky
    }

    /// The world of a kind.
    static func world(_ kind: Kind) -> SkyWorld {
        switch kind {
        case .duo: return duo
        case .slab: return slab
        }
    }

    /// The boxes his stars are laid out in, looking up. `stripWindow` is
    /// where the Duo's strip window begins (the lab's own when nil): fewer
    /// stars stand in it, where tonight's star is to be the one bright thing
    /// with a little company. Low down, the part of the sky the REST pose
    /// shows in the header band and the strip is never empty.
    ///
    /// The header's gap (x 207 – 313 on the Duo, 206 – 337 on the slab) and
    /// the header's words (x under 116 at rest) are THE LAB'S LAYOUT too.
    func starBoxes(stripWindow: CGFloat? = nil) -> [StarBox] {
        let xMin = starInset
        let xMax = anchor.width - starInset
        switch kind {
        case .duo:
            let strip = stripWindow ?? labStripWindow ?? anchor.width
            return [
                StarBox(x0: 207, x1: 313, y0: starTop, y1: 97, density: 0.85, columns: []),
                StarBox(x0: xMin, x1: strip + 16, y0: 99, y1: 187, density: 0.80, columns: []),
                StarBox(x0: xMin, x1: xMax, y0: 187, y1: drop, density: 0.70, columns: [
                    .init(x0: xMin, x1: strip, weight: 1),
                    .init(x0: strip, x1: xMax, weight: 0.85),
                ]),
                // At rest this band is the header: its words and buttons
                // stand at x < 116 here, its clear gap at 116 – 232.
                StarBox(x0: xMin, x1: xMax, y0: drop, y1: drop + 88, density: 0.95, columns: [
                    .init(x0: xMin, x1: 116, weight: 0.12),
                    .init(x0: 116, x1: 232, weight: 1.7),
                    .init(x0: 232, x1: strip, weight: 0.9),
                    .init(x0: strip, x1: xMax, weight: 0.55),
                ]),
                // At rest: the strip, beside the tree.
                StarBox(x0: xMin, x1: strip + 22, y0: drop + 88, y1: horizonUp - 10, density: 0.70, columns: [
                    .init(x0: xMin, x1: strip - turn, weight: 0.7),
                    .init(x0: strip - turn, x1: strip + 14, weight: 2.3),
                    .init(x0: strip + 14, x1: strip + 22, weight: 0.5),
                ]),
            ]
        case .slab:
            return [
                StarBox(x0: 206, x1: 337, y0: starTop, y1: 138, density: 0.75, columns: []),
                StarBox(x0: xMin, x1: xMax, y0: 146, y1: drop + 60, density: 0.50, columns: []),
                // At rest: the header's small landscape.
                StarBox(x0: xMin, x1: xMax, y0: drop + 60, y1: horizonUp - 8, density: 1.05, columns: [
                    .init(x0: xMin, x1: 160, weight: 0.5),
                    .init(x0: 160, x1: anchor.width - turn, weight: 1.5),
                    .init(x0: anchor.width - turn, x1: xMax, weight: 0.5),
                ]),
            ]
        }
    }
}

// MARK: - The displays

extension SkyWorld {
    /// A display the world is seen through. The picture is anchored to the
    /// phone page — the anchor window — so the Duo's cover and the spread's
    /// phone page show the same sky, and opening the Duo widens it.
    struct Display: Equatable {
        /// The whole display.
        let size: CGSize
        /// The anchor window: where the phone page's leading edge is, and how
        /// wide the page is.
        let anchorX: CGFloat
        /// The anchor window's width: the world's own.
        let anchorWidth: CGFloat
        /// The system strip's width along the trailing edge (the Duo's).
        let strip: CGFloat?
        /// Where the fold's crease is (the open Duo's).
        let fold: CGFloat?
        /// Which world it is a window on.
        let kind: Kind

        /// The world it is a window on.
        var world: SkyWorld { SkyWorld.world(kind) }

        /// The Duo closed: 466 × 678, the world from its leading edge.
        static let cover = Display(size: CGSize(width: 466, height: 678), anchorX: 0, anchorWidth: 466,
                                   strip: 84, fold: nil, kind: .duo)
        /// The Duo open in landscape: 951 × 669. The phone page keeps the
        /// cover's sky where it was, and the world runs on to the left.
        static let spread = Display(size: CGSize(width: 951, height: 669), anchorX: 485, anchorWidth: 466,
                                    strip: 84, fold: 475.5, kind: .duo)
        /// A slab iPhone: 402 × 874, the only size its world was set for.
        static let slab = Display(size: CGSize(width: 402, height: 874), anchorX: 0, anchorWidth: 402,
                                  strip: nil, fold: nil, kind: .slab)
    }
}

